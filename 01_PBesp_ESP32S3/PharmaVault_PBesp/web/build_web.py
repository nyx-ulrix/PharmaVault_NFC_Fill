"""Regenerate the compressed web assets compiled into the pillbox firmware.

Run after editing the dashboard HTML in PharmaVault_PBesp.ino or web/mascot.webp:
    python web/build_web.py
Writes PvDashboardGz.h (gzipped dashboard) and PvMascot.h next to the sketch.
The sketch static_asserts the HTML length, so a forgotten rebuild fails to compile.
"""
import gzip, os

HERE = os.path.dirname(os.path.abspath(__file__))
SKETCH = os.path.dirname(HERE)


def c_array(name, data):
    rows = [",".join(str(b) for b in data[i:i + 40]) for i in range(0, len(data), 40)]
    return f"static const uint8_t {name}[{len(data)}] PROGMEM = {{\n" + ",\n".join(rows) + "\n};\n"


def write_header(fname, guard, body):
    text = (f"// Generated by web/build_web.py. Do not edit by hand.\n#ifndef {guard}\n#define {guard}\n"
            f"#include <pgmspace.h>\n{body}#endif\n")
    with open(os.path.join(SKETCH, fname), "w", newline="\r\n") as f:
        f.write(text)


def dashboard_html():
    src = open(os.path.join(SKETCH, "PharmaVault_PBesp.ino"), encoding="utf-8").read()
    start = src.index('R"PVHTML(') + len('R"PVHTML(')
    html = src[start:src.index(')PVHTML"')].replace("\r\n", "\n")  # compilers see LF line ends
    return html.encode("utf-8")


if __name__ == "__main__":
    html = dashboard_html()
    gz = gzip.compress(html, 9, mtime=0)
    assert gzip.decompress(gz) == html
    write_header("PvDashboardGz.h", "PHARMAVAULT_DASHBOARD_GZ_H",
                 f"#define PV_DASHBOARD_SRC_LEN {len(html)}\n" + c_array("PvDashboardGz", gz))
    mascot = open(os.path.join(HERE, "mascot.webp"), "rb").read()
    write_header("PvMascot.h", "PHARMAVAULT_MASCOT_H", c_array("PvMascotWebp", mascot))
    print(f"dashboard {len(html)} -> {len(gz)} bytes gzipped; mascot {len(mascot)} bytes")
